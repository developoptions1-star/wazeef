#!/usr/bin/env node
// Pre-build script: embeds HTML pages and image assets into a single JS module
// so the server has ZERO dependency on the filesystem for page serving.
const fs = require('fs');
const path = require('path');

const PUB = path.join(__dirname, 'public');
const OUT = path.join(__dirname, 'pages.js');

const pages = {};
['login.html', 'dashboard.html', 'admin.html', 'agent.html', 'company.html'].forEach(f => {
  pages[f] = fs.readFileSync(path.join(PUB, f), 'utf8');
});

const images = {};
const uploadsDir = path.join(PUB, 'uploads');
if (fs.existsSync(uploadsDir)) {
  fs.readdirSync(uploadsDir).forEach(f => {
    const ext = path.extname(f).toLowerCase();
    if (['.png', '.jpg', '.jpeg', '.gif', '.svg', '.ico', '.webp'].includes(ext) && f !== 'wazef1.png' && f !== 'wazef-mobile.png') {
      const data = fs.readFileSync(path.join(uploadsDir, f));
      const mime = { '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.gif': 'image/gif', '.svg': 'image/svg+xml', '.ico': 'image/x-icon', '.webp': 'image/webp' }[ext] || 'application/octet-stream';
      images[f] = { mime, base64: data.toString('base64') };
    }
  });
}

// Also embed favicon.svg if it exists
const faviconPath = path.join(PUB, 'favicon.svg');
if (fs.existsSync(faviconPath)) {
  images['favicon.svg'] = { mime: 'image/svg+xml', base64: fs.readFileSync(faviconPath).toString('base64') };
}

// Text/config assets - production containers have no public/ on disk, so these
// must travel inside pages.js too (robots/sitemap/manifest/sw all 500 otherwise).
const assets = {};
['robots.txt', 'sitemap.xml', 'manifest.json', 'sw.js', 'i18n-data.js'].forEach(f => {
  const p = path.join(PUB, f);
  if (fs.existsSync(p)) assets[f] = fs.readFileSync(p, 'utf8');
});

// The i18n dictionary is too big to inline 5x - it is served as an asset and
// referenced with a tag that must run BEFORE the engine script.
const i18nTag = fs.existsSync(path.join(PUB, 'i18n-data.js'))
  ? '<script src="/i18n-data.js"></script>' : '';

// Inject shared scripts (lang picker) into every page so serving stays filesystem-free
const sharedScripts = ['lang-picker.js', 'notify.js', 'session.js', 'site-i18n.js']
  .filter(f => fs.existsSync(path.join(PUB, f)))
  .map(f => fs.readFileSync(path.join(PUB, f), 'utf8'))
  .map(js => '<script>\n' + js + '\n</script>')
  .join('\n');
if (sharedScripts || i18nTag) {
  const inject = (i18nTag + '\n' + sharedScripts).trim();
  Object.keys(pages).forEach(f => {
    if (pages[f].indexOf('</head>') !== -1) {
      pages[f] = pages[f].replace('</head>', inject + '\n</head>');
    } else {
      pages[f] = inject + '\n' + pages[f];
    }
  });
}

const code = `// AUTO-GENERATED by build-pages.js - DO NOT EDIT
const pages = ${JSON.stringify(pages)};
const images = ${JSON.stringify(images)};
const assets = ${JSON.stringify(assets)};
module.exports = { pages, images, assets };
`;

fs.writeFileSync(OUT, code, 'utf8');
const sizeKB = (Buffer.byteLength(code) / 1024).toFixed(1);
console.log('build-pages: Generated pages.js (' + sizeKB + ' KB)');
console.log('  Pages:', Object.keys(pages).join(', '));
console.log('  Images:', Object.keys(images).join(', '));
console.log('  Assets:', Object.keys(assets).join(', '));
